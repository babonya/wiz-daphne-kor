def _mg_v_cap(adj_speeds):
    """이 판의 속도 상한(px/ms). adj_speeds = 이 판에서 본 인접쌍 |v| 목록(판을 넘기지 않는다).

    🔴 표본이 모자라면 고정 초기 상한(_MG_V_MAX_PX_MS)을 쓴다 - 초반에 가짜 속도로 쏘지 않는다.
    🔴 통계가 서도 _MG_V_ABS_MAX_PX_MS 를 절대 넘지 않는다(중앙값이 오염되는 경우의 바닥).
    🔴 판 사이 학습이 아니다 - 호출부가 판마다 빈 목록에서 다시 센다.
    """
    if not adj_speeds or len(adj_speeds) < _MG_V_CAP_MIN_SAMPLES:
        return _MG_V_MAX_PX_MS
    s = sorted(adj_speeds)
    med = s[len(s) // 2]
    if not (med > 0.0):
        return _MG_V_MAX_PX_MS
    return min(_MG_V_ABS_MAX_PX_MS, _MG_V_CAP_K * med)


def _mg_estimate_v(samples, max_gap_ms, v_cap=None):
    """최근 표본 [(x, t초), ...] 로 막대 속도(px/ms)를 추정한다. 못 믿으면 (None, 사유).

    🔴 [2026-09-20 (2)] 속도값은 **표본 창 전체의 최소제곱 기울기**다(구: 인접 쌍 3개 평균).
       근거는 _MG_MIN_BASELINE_MS 주석. 요약하면 인접 쌍은 기준선이 26ms 뿐인데 유효
       시간오차가 ±16ms 급이라 원리적으로 못 쓴다.
    🔴 **부호 반전·시간 공백은 지금도 인접 쌍으로 본다.** 그건 짧은 기준선이 맞다 -
       반환점을 늦게 알아채면 가짜 속도로 쏘게 된다. 속도값만 긴 기준선으로 바꾼 것이다.
    🔴 양 끝점 방식도 실 CSV 로 대조했다(18판 · 같은 창 · 같은 게이트 · 창 2,181개):
       상대오차 중앙 9.06%(최소제곱) vs 8.37%(양끝) · p95 30.2% vs 28.4% = **사실상 동률**이고,
       갈리는 곳은 꼬리다 — 최악값 83.8% vs 93.1% 로 최소제곱이 낫다(양 끝점은 두 점 중 하나만
       튀면 그대로 반영된다). 두 번째 이유는 아래 잔차 게이트다: 양 끝점 적합은 끝점 잔차가
       정의상 0 이라 게이트가 무뎌진다. 그래서 최소제곱을 쓴다.

    사유: 'few' 표본 부족 **또는 기준선 부족** · 'gap' 시간 공백 · 'stall' 정지 ·
          'flip' 부호 반전(양 끝 반환) · 'vmax' 속도 상한 초과 · 'resid' 적합 잔차 과다.
    🔴 어느 경우든 쏘지 않는다. 모르면 기다리는 게 언제나 이득이다.
    🔴 'resid' 가 구 'spread' 의 역할을 그대로 잇는다 - 가짜 속도를 막는 게이트다.
       없애면 -3.75 같은 값으로 쏘게 된다.
    """
    if len(samples) < _MG_MIN_SAMPLES:
        return None, 'few'
    # 🔴 개수만으로는 부족하다 - 기준선(창 전체 시간)이 짧으면 기울기가 잡음에 묻힌다.
    if (samples[-1][1] - samples[0][1]) * 1000.0 < _MG_MIN_BASELINE_MS:
        return None, 'few'

    # 1) 인접 쌍 검사 - 시간 공백 · 정지 · 부호 반전(반환점)만 본다.
    sgn = 0
    moved = False
    for (x0, t0), (x1, t1) in zip(samples, samples[1:]):
        dt_ms = (t1 - t0) * 1000.0
        if dt_ms <= 0.0 or dt_ms > max_gap_ms:
            return None, 'gap'
        dx = x1 - x0
        if dx == 0.0:
            # 🔴 60fps 격자 위에서는 같은 x 가 연속으로 들어오는 게 정상이다
            #    (틱당 양자 수 ~1.6). 그걸 '정지'로 보면 멀쩡한 창을 통째로 버린다.
            #    정지 판정은 창 전체가 안 움직였을 때만 한다(아래 moved).
            continue
        moved = True
        s = 1 if dx > 0 else -1
        if sgn == 0:
            sgn = s
        elif s != sgn:
            return None, 'flip'
    if not moved:
        return None, 'stall'

    # 2) 속도값 = 창 전체 최소제곱 기울기(기준선이 길수록 시간 잡음에 강하다).
    n = len(samples)
    t0 = samples[0][1]
    ts = [(t - t0) * 1000.0 for _, t in samples]
    xs = [x for x, _ in samples]
    t_bar = sum(ts) / n
    x_bar = sum(xs) / n
    s_tt = sum((t - t_bar) ** 2 for t in ts)
    if s_tt <= 0.0:
        return None, 'gap'
    v = sum((x - x_bar) * (t - t_bar) for x, t in zip(xs, ts)) / s_tt
    if v == 0.0:
        return None, 'stall'
    cap = _MG_V_MAX_PX_MS if v_cap is None else v_cap
    if abs(v) > cap:
        return None, 'vmax'

    # 3) 적합 잔차 게이트(구 'spread' 대체). 잔차 RMS 를 |v| 로 나누면 ms 단위가 되므로
    #    속도와 무관하게 같은 임계 하나로 판정할 수 있다.
    #    🔴 이 게이트를 풀면 -3.75px/ms 같은 쓰레기 추정으로 쏘게 된다. 완화 금지.
    b0 = x_bar - v * t_bar
    ss = sum((x - (b0 + v * t)) ** 2 for x, t in zip(xs, ts))
    if (ss / n) ** 0.5 / abs(v) > _MG_V_FIT_RESID_MS:
        return None, 'resid'
    return v, ''


def _mg_strip_offsets(y1, y2, w):
    """띠(y1~y2)를 screencap 원시 스트림에서 뽑기 위한 dd 파라미터 계산(순수 함수).

    반환 (skip, lead, count, want_len).
    1440x2560 · y84~190 -> (118, 524, 150, 610560) [실측 검증값]
    """
    want_off = 12 + y1 * w * 4               # 12 = screencap 헤더(width,height,format)
    want_len = (y2 - y1) * w * 4
    skip = want_off // _MG_BS                # dd 블록 단위
    lead = want_off - skip * _MG_BS          # 블록 앞쪽 버릴 바이트
    count = -(-(want_len + lead) // _MG_BS)  # ceil
    return skip, lead, count, want_len


def _mg_grab_strip(device, y1, y2, w, h):
    """미니게임 바 띠만 기기에서 잘라 받는다. (y2-y1, w, 4) RGBA 배열 반환.
    실패하면 None -> 호출부가 전체 캡처로 폴백한다.

    🔴 device.shell() 은 텍스트를 돌려주므로 못 쓴다. screen_capture.capture_screen_bytes 와
       동일하게 create_connection() + send("exec:...") + read_all() 로 바이너리를 받는다.
    🔴 채널 순서는 전체 캡처와 동일한 RGBA([...,0]=R). 뒤집지 않는다.
    """
    if device is None or w <= 0 or y1 < 0 or y2 <= y1 or y2 > h:
        return None
    skip, lead, count, want_len = _mg_strip_offsets(y1, y2, w)
    try:
        cmd = (f"exec:screencap > /data/local/tmp/_s.raw; "
               f"dd if=/data/local/tmp/_s.raw bs={_MG_BS} skip={skip} count={count} 2>/dev/null")
        conn = device.create_connection()
        with conn:
            conn.send(cmd)
            d = bytes(conn.read_all())
        if len(d) < lead + want_len:
            return None          # dd 없음·실패·조기 종료 -> 전체 캡처로 폴백
        return np.frombuffer(d[lead:lead + want_len], dtype=np.uint8).reshape((y2 - y1, w, 4)).copy()
    except Exception:
        return None


def _mg_runs(mask):
    """1차원 bool 마스크에서 연속 True 덩어리를 [(시작, 끝), ...] 로 뽑는다(끝 포함)."""
    edges = np.flatnonzero(np.diff(np.concatenate(([0], mask.astype(np.int8), [0]))))
    return [(int(edges[i]), int(edges[i + 1]) - 1) for i in range(0, len(edges), 2)]


def _mg_scan_row(img_np, y_off=0, full_h=None):
    """스캔줄 한 줄을 RGB 정수 채널로 분해해 돌려준다(4채널 RGBA 입력도 그대로 처리).

    띠 크롭 배열은 y 가 0부터 시작하므로 원본 기준 스캔줄에서 y_off(띠 시작 y)를 뺀다.
    full_h = 원본 화면 높이(띠 높이가 아니다). 생략하면 입력 배열 높이 = 전체 화면으로 본다.
    """
    h = img_np.shape[0] if full_h is None else full_h
    y = int(_MG_SCAN_Y * (h / 2560.0)) - y_off
    y = max(0, min(img_np.shape[0] - 1, y))
    row = img_np[y]
    return row[:, 0].astype(np.int16), row[:, 1].astype(np.int16), row[:, 2].astype(np.int16)


# 🔬 [2026-09-20] 마지막 _mg_find_zones 호출의 '병합 후 · 폭 필터 전' 덩어리 폭 목록.
#    이게 없으면 "구간 0개"가 (가)노란 픽셀 자체가 없음 인지 (나)있었는데 좁아서 기각됨 인지
