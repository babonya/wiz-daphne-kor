_ABOVE_NORMAL_PRIORITY_CLASS = 0x00008000   # winbase.h. 아래 ffmpeg Popen 의 creationflags 로도 쓴다
_HIGH_PRIORITY_CLASS = 0x00000080
_REALTIME_PRIORITY_CLASS = 0x00000100

def _raise_own_priority():
    """자기 프로세스를 ABOVE_NORMAL 로 올린다. 실패는 조용히 삼킨다(없어도 봇은 돌아간다)."""
    try:
        import ctypes
        # 🔴 restype/argtypes 를 반드시 박는다. 기본값(c_int)으로 두면 GetCurrentProcess 의
        #    의사 핸들 (HANDLE)-1 이 64비트에서 잘려 0x00000000FFFFFFFF 로 넘어가고,
        #    GetPriorityClass 가 조용히 0(실패)을 돌려준다 — 실측으로 확인했다.
        #    windll 대신 WinDLL 인스턴스를 새로 잡아 공유 함수 객체를 건드리지 않는다.
        k32 = ctypes.WinDLL("kernel32")       # 윈도우가 아니면 여기서 터진다 -> except 로 무시
        k32.GetCurrentProcess.restype = ctypes.c_void_p
        k32.GetPriorityClass.argtypes = [ctypes.c_void_p]
        k32.GetPriorityClass.restype = ctypes.c_uint32
        k32.SetPriorityClass.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
        h = k32.GetCurrentProcess()
        cur = k32.GetPriorityClass(h)         # 0 = 조회 실패. 그땐 그냥 설정을 시도한다
        if cur in (_ABOVE_NORMAL_PRIORITY_CLASS, _HIGH_PRIORITY_CLASS, _REALTIME_PRIORITY_CLASS):
            return                            # 이미 충분히 높다 — 내리면 손해다
        k32.SetPriorityClass(h, _ABOVE_NORMAL_PRIORITY_CLASS)
    except Exception:
        pass

_raise_own_priority()

