    if mode not in ("auto", "macrobox", "lowspec", "manual", "none"):
        mode = "auto"
    _AIM_CALIB_MODE = mode
    if mode == "none":
        if verbose:
            print("🔨 [상자 조준 영점] 모드=none · 조준 끔 - 미니게임은 예전처럼 해제 버튼 15연타(횟수 제한 없음, ffmpeg 불필요)")
        return
    if mode == "manual":
        base = AIM_CALIB_PRESETS["macrobox"]
        _MG_GLIDE_PX = float(glide_px) if glide_px is not None else base[0]
        _MG_LATENCY_MS = float(latency_ms) if latency_ms is not None else base[1]
        _MG_JITTER_MS = float(jitter_ms) if jitter_ms is not None else base[2]
        src_txt = "직접 입력"
    elif mode in AIM_CALIB_PRESETS:
        _MG_GLIDE_PX, _MG_LATENCY_MS, _MG_JITTER_MS = AIM_CALIB_PRESETS[mode]
        src_txt = "매크로박스 고정" if mode == "macrobox" else "저사양 PC 고정"
    else:
        _MG_GLIDE_PX, _MG_LATENCY_MS, _MG_JITTER_MS = AIM_CALIB_PRESETS["macrobox"]
        samples = _aim_calib_load()
        fit = _aim_calib_refit(samples)
        if fit:
            _MG_GLIDE_PX, _MG_LATENCY_MS, _MG_JITTER_MS, _ = fit
            src_txt = f"자동(누적 표본 {len(samples)}발로 보정됨)"
        else:
            src_txt = f"자동(표본 {len(samples)}/{AIM_AUTO_MIN_SAMPLES}발 - 모일 때까지 매크로박스 값 사용)"
    if verbose:
        print(f"🎯 [상자 조준 영점] 모드={mode} · {src_txt} · 활공 {_MG_GLIDE_PX:.1f}px + "
              f"{_MG_LATENCY_MS:.0f}ms x |v| · 지터 바닥 {_MG_JITTER_MS:.0f}ms")


