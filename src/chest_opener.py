#    🔴 _mg_find_zones 는 스레드에서 부르지 않으므로 전역 한 칸이면 충분하다(락 불필요).
_MG_LAST_MERGED_W = []


def _mg_find_zones(img_np, y_off=0, full_h=None):
    """스캔줄의 노란 안전구간을 [(좌, 우), ...] 로 반환한다(현재 해상도 픽셀 좌표).

    y_off·full_h = 띠 크롭 입력용(_mg_find_bar_x 와 동일 규약). 생략하면 전체 프레임으로 본다.
    부수효과: 기각분까지 포함한 덩어리 폭을 _MG_LAST_MERGED_W 에 남긴다(진단 전용 · 판정 무관).
    """
    global _MG_LAST_MERGED_W
    if img_np is None or img_np.ndim != 3 or img_np.shape[2] < 3:
        _MG_LAST_MERGED_W = []
        return []
    scale_x = img_np.shape[1] / 1440.0
    r, g, b = _mg_scan_row(img_np, y_off, full_h)
    yellow = (r > 200) & (g > 110) & (g < 210) & (b < 110)

    merged = []
    for lo, hi in _mg_runs(yellow):
        if merged and (lo - merged[-1][1] - 1) <= _MG_ZONE_MERGE_GAP * scale_x:
            merged[-1][1] = hi   # 막대가 구간 한가운데를 가리고 있을 때 다시 잇는다
        else:
            merged.append([lo, hi])
    _MG_LAST_MERGED_W = [hi - lo + 1 for lo, hi in merged]
    return [(lo, hi) for lo, hi in merged if (hi - lo + 1) >= _MG_ZONE_MIN_W * scale_x]


def _mg_zones_changed(old, new):
    """구간이 '로그를 찍을 만큼' 바뀌었는가. 🔴 표시 전용 - zones 갱신 여부와는 무관하다.

    구간 개수가 달라졌거나(페이드인 조각 3개 -> 진짜 2개) 경계가 _MG_ZONE_LOG_MOVE_PX 이상
    움직인 경우만 True. 정상 점등 중의 1~35px 지터는 False = 조용하다.
    """
    if len(old) != len(new):
        return True
    return any(abs(o[e] - n[e]) >= _MG_ZONE_LOG_MOVE_PX
               for o, n in zip(old, new) for e in (0, 1))


def _mg_zones_stable(old, new, tol_px=_MG_ZONE_LOCK_TOL_PX):
    """두 스캔 결과가 '사실상 같은가' = 구간 개수 동일 + 모든 구간 중심이 tol_px 이내.

    🔴 중심으로 본다(경계가 아니라). 막대가 구간 한쪽 끝을 가리면 경계는 크게 흔들려도
       중심은 거의 안 움직인다 — 잠금은 '같은 화면인가'를 묻는 것이지 '몇 px 움직였나'가 아니다.
    """
    if not old or not new or len(old) != len(new):
        return False
    return all(abs((o[0] + o[1]) - (n[0] + n[1])) / 2.0 <= tol_px for o, n in zip(old, new))


def _mg_zones_overlap_any(locked, fresh):
    """새 스캔 구간 중 **하나라도** 잠긴 구간과 겹치는가. 전부 안 겹치면 화면이 바뀐 것이다."""
    if not locked or not fresh:
        return False
    return any(lo <= h and l <= hi for lo, hi in locked for l, h in fresh)


def _mg_alive_zone_count(locked_zones, fresh):
    """'아직 미니게임 중인가' 를 판정할 때 세는 구간 개수. locked_zones=None 이면 아직 잠금 전.

    🔴 **종료 판정 전용**이다(_MG_ALIVE_MIN_ZONES 와 짝). 조준·발사·구간 갱신에는 쓰지 않는다.

    🔴 구간 잠금과의 합성 규칙 — 셋 중 하나를 골라야 했고 근거는 이렇다:
      (가) 잠긴 구간을 그대로 센다      -> **기각**. 잠금은 그 판 동안 안 변하므로 항상 2개 =
           막대 실종 탈출이 영원히 안 걸린다. 정산 연출 화면에서 6초를 통째로 태운다.
      (나) 재스캔 결과 fresh 개수를 센다 -> 잠금 전에는 이것뿐이라 이걸 쓴다. 다만 잠금 후에는
           위험하다 — 미니게임이 끝난 뒤 화면의 잡다한 노란 것들(상자 빛 등)이 실기동에서
           폭 60~634 로 2개 이상 잡혔다(그게 6초를 태운 그 판이다). 그걸 '살아 있다' 로 둔갑시킨다.
      (다) **잠긴 구간 중 지금도 불이 켜져 있는 것의 수** -> 잠금 후에는 이것을 쓴다.
           '진짜 구간 자리에 아직 불이 있는가' 만 묻는다. 잡다한 노란 것은 자리가 달라 안 세어지고,
           진짜 미니게임이 살아 있으면 두 자리가 다 켜져 있어 2개가 된다.
    🔴 잠금 로직 자체는 건드리지 않는다 — 여기서는 읽기만 한다.
    """
    if locked_zones is None:
        return len(fresh)
    if not fresh:
        return 0
    return sum(1 for lo, hi in locked_zones if any(l <= hi and lo <= h for l, h in fresh))


def _mg_find_bar_x(img_np, y_off=0, full_h=None):
    """스캔줄에서 흰 막대(세 채널 >= 200) 덩어리의 중심 x. 못 찾으면 None(= 표본 버림).

    y_off·full_h = 띠 크롭 입력용(크롭 배열의 y 는 0부터 시작 -> 스캔줄 = scan_y - y_off).

    🔴 막대의 실제 왕복 범위는 명세가 적은 178~1305 가 아니라 화면 전체(약 0~1439)다
       (167프레임 실측 - 양 끝에서 화면 밖으로 잘린다). 그래서 x 범위 게이트는 두지 않고,
       대신 **화면 좌우 끝에 닿아 잘린 덩어리는 버린다** - 잘리면 중심이 거짓말을 하고
       (실측: 프레임19 에서 중심이 1430 으로 밀림) 그 거짓 중심이 속도를 2배로 부풀린다.
    """
    if img_np is None or img_np.ndim != 3 or img_np.shape[2] < 3:
        return None
    w = img_np.shape[1]
    scale_x = w / 1440.0
    r, g, b = _mg_scan_row(img_np, y_off, full_h)
    white = (r >= 200) & (g >= 200) & (b >= 200)

    best = None
    for lo, hi in _mg_runs(white):
        wid = hi - lo + 1
        if wid < _MG_BAR_MIN_W * scale_x or wid > _MG_BAR_MAX_W * scale_x:
            continue
        if lo <= 0 or hi >= w - 1:
            continue          # 화면 밖으로 잘린 막대 - 중심을 못 믿는다
        if best is None or wid > best[0]:
            best = (wid, (lo + hi) / 2.0)
    return None if best is None else best[1]


def _mg_glide_px(v):
    """탭 이후 막대가 진행방향으로 더 미끄러지는 거리(px · 항상 양수). 2모수 모델의 본체.

    고정 활공 + 지연 x 속도. v 부호는 방향일 뿐이라 여기서는 크기만 쓴다.
    """
    return _MG_GLIDE_PX + _MG_LATENCY_MS * abs(v)


def _mg_predict_land(x, v, frame_age_ms):
    """착지 예측 — 🔴 발사 조건과 명중창 판정이 **반드시 이 한 군데**를 같이 쓴다.

    프레임 나이와 탭 이후는 성질이 다르므로 분리한다:
      · frame_age_ms (프레임이 파이썬에 들어온 뒤 흐른 시간) 동안은 막대가 진짜로 v 만큼 움직인다.
      · 탭 이후는 속도와 무관한 고정 활공 + 속도에 비례하는 몫만큼 진행방향으로 더 간다.
    """
    sgn = 1.0 if v > 0 else -1.0
    return x + v * frame_age_ms + sgn * _mg_glide_px(v)


def _mg_sigma_ms(dt_hist):
    """착지 산포 sigma(ms) 와 '적응이 걸렸나' 를 돌려준다 — `(sigma_ms, 적응여부)`.

    sigma_ms = max(_MG_JITTER_MS, 최근 프레임간격 p95). 근거는 _MG_JITTER_WINDOW 위 주석.

    🔴 p95 는 **nearest-rank**(정렬 후 index = ceil(0.95n)-1)다. 보간식(numpy 기본)을 쓰지 않는
       이유는 두 가지다 — (가) 표본이 최대 20개라 보간해 봐야 이웃 두 값 사이일 뿐이고,
       (나) 이 판정은 frames.csv 로 오프라인 재생해 검산하는데 재생기와 코드가 **같은 식**이어야
       표가 의미를 갖는다. 정수 연산 `-(-(95*n)//100)` = ceil(95n/100) 이라 부동소수 오차도 없다.
    🔴 dt_hist 가 비어 있어도 안전하다(길이 검사가 먼저다). 호출부는 판마다 새 목록을 준다.
    """
    n = len(dt_hist)
    if n < _MG_JITTER_MIN_SAMPLES:
        return _MG_JITTER_MS, False
    idx = max(0, min(n - 1, -(-(95 * n) // 100) - 1))
    p95 = sorted(dt_hist)[idx]
    if p95 > _MG_JITTER_MS:
        return p95, True
    return _MG_JITTER_MS, False


