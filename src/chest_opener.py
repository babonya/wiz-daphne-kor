            #       이면 무조건 '아직 중앙 전' 으로 빠진다. 즉 표본이 없으면 안 쏜다(안전한 쪽).
            #    🔴 여기를 '지나침 허용'으로 완화하지 마라 - 지나친 뒤의 탭은 확실히 빗나간다.
            dt_ms = ((xt[-1][1] - xt[-2][1]) * 1000.0 if len(xt) >= 2 else 0.0)
