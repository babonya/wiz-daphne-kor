_MG_SAME_FRAME = object()   # latest(since_ts) 의 '아직 새 프레임이 아니다' 표식(복사 안 함). None 과 구분해야 한다.


class _MgStream:
    """미니게임용 바 띠 전용 H.264 스트림. 최신 프레임 1장만 들고 있는다.

    adb 소켓(screenrecord h264) --수신스레드--> ffmpeg stdin
    ffmpeg stdout(띠만 크롭한 rawvideo) --읽기스레드--> 최신 프레임 1장 교체(큐에 쌓지 않는다)
    """

    def __init__(self):
        self._lock = threading.Lock()
        self._frame = None
        self._ts = 0.0
        self._proc = None
        self._conn = None
        self._evt = None
        self._threads = []
        self._last_use = 0.0     # 마지막으로 latest() 가 불린 시각(유휴 회수 시계)
        self._first_ts = 0.0     # 이번 실행분의 첫 프레임 시각. 0 = 아직 기동 중(회수 금지)
        self._reaped = False     # _feed 가 유휴로 스스로 내렸다 -> running() 이 False

    @staticmethod
    def _ffmpeg_path():
        """ffmpeg 실행파일 경로. 없으면 None -> start() 가 False -> 기존 screencap 경로."""
        found = shutil.which("ffmpeg")
        if found:
            return found
        return _MG_FFMPEG_FALLBACK if os.path.exists(_MG_FFMPEG_FALLBACK) else None

    def start(self, device, w, h, y1, y2):
        """띠(y1~y2) 스트림을 띄운다. 성공 True / 실패 False(호출부는 무시하고 폴백으로 진행)."""
        self.stop()                      # 이전 스트림이 남아 있으면 먼저 정리(좀비 금지)
        if device is None or w <= 0 or h <= 0 or y1 < 0 or y2 <= y1 or y2 > h:
            return False
        ff = self._ffmpeg_path()
        if ff is None:
            return False
        strip_h = y2 - y1
        nbytes = w * strip_h * 3
        # 🔴 명세 실측 커맨드 그대로. 인자를 바꾸면(특히 -fps_mode passthrough 를 빼면) 전부 무너진다.
        #    stderr 는 DEVNULL - 아무도 안 읽는 파이프에 ffmpeg 로그가 차면 ffmpeg 이 막힌다.
        argv = [ff, "-fflags", "nobuffer", "-flags", "low_delay", "-f", "h264", "-i", "pipe:0",
                "-fps_mode", "passthrough", "-vf", f"crop={w}:{strip_h}:0:{y1}",
                "-f", "rawvideo", "-pix_fmt", "rgb24", "-flush_packets", "1", "pipe:1"]
        # 🔴 ffmpeg 도 ABOVE_NORMAL 로 띄운다 — 디코딩이 밀리면 프레임나이가 그대로 튀고,
        #    그게 곧 명중률이다. (여기엔 원래 creationflags 가 없었다. 나중에 다른 플래그를
        #    붙일 일이 생기면 반드시 `|` 로 합칠 것 — 통째로 덮어쓰면 우선순위가 사라진다.)
        try:
            proc = subprocess.Popen(argv, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                    stderr=subprocess.DEVNULL, bufsize=0,
                                    creationflags=_ABOVE_NORMAL_PRIORITY_CLASS)
        except Exception:
            return False
        conn = None
        try:
            conn = device.create_connection(timeout=_MG_STREAM_SOCK_TIMEOUT_S)
            conn.send(f"exec:screenrecord --output-format=h264 --size {w}x{h} "
                      f"--bit-rate 10M --time-limit {_MG_STREAM_TIME_LIMIT_S} -")
        except Exception:
            self._close_conn(conn)
            self._kill_proc(proc)
            self._close_pipes(proc)      # 아직 스레드가 없으니 여기서 바로 닫아도 안전하다
            return False

        evt = threading.Event()          # 스레드는 자기 실행분의 이벤트만 본다(재기동해도 안 섞인다)
        self._proc, self._conn, self._evt = proc, conn, evt
        # 🔴 유휴 시계 초기화는 반드시 스레드 기동 전에. stop() 이 이미 위에서 옛 스레드를 거뒀으므로
        #    여기서 쓰는 값을 옛 _feed 가 덮어쓸 수 없다.
        self._reaped = False
        with self._lock:
            self._last_use = time.time()
            self._first_ts = 0.0
        self._threads = [
            threading.Thread(target=self._feed, args=(conn, proc, evt), daemon=True),
            threading.Thread(target=self._read, args=(proc, strip_h, w, nbytes, evt), daemon=True),
        ]
        for t in self._threads:
            t.start()
        return True

    def latest(self, since_ts=0.0):
        """(프레임, 찍힌 시각) / _MG_SAME_FRAME(이미 쓴 그 프레임) / None(쓸 게 없다).

        🔴 낡은 프레임은 절대 돌려주지 않는다.
        🚀 [2026-09-20] since_ts = 호출부가 마지막으로 쓴 프레임의 시각. 같으면 **복사하기 전에**
           _MG_SAME_FRAME 을 돌려준다. 예전에는 458KB(1440x106x3)를 복사해 놓고 호출부가
           타임스탬프를 보고 그냥 버렸다 — 2ms 폴링이라 초당 약 500회 × 458KB = 229MB/s 헛 복사에
           그동안 락까지 쥐고 있어 _read 스레드를 굶길 수 있었다.
        🔴 세 결과를 뭉뚱그리면 안 된다 — '같은 프레임'은 2ms 쉬고 다시 폴링(스트림 유지)이고,
           None 은 띠 screencap 으로 내려가라는 뜻이다. 합치면 폴링마다 110ms 캡처가 터진다.
        """
        with self._lock:
            # 🔴 프레임이 없든 낡았든 같은 프레임이든 '불렸다'는 사실 자체가 사용 신호다
            #    (기동 중 대기도, 같은 프레임 폴링도 '쓰는 중'이다 — 여기서 갱신을 빼먹으면
            #     폴링 도중에 _feed 의 유휴 회수가 스트림을 스스로 내린다).
            #    락 안에서 갱신해야 _feed 의 유휴 검사와 찢어지지 않는다.
            self._last_use = time.time()
            if self._frame is None:
                return None
            ts = self._ts
            if ts == since_ts:
                return _MG_SAME_FRAME       # 🚀 복사하지 않고 락도 곧장 놓는다
            if (time.time() - ts) * 1000.0 > _MG_STREAM_STALE_MS:
                return None
            return self._frame.copy(), ts   # 읽는 중에 덮어써도 찢어지지 않게 복사해서 준다

    def has_frame(self):
        """🆕 [2026-09-28] 이번 실행분의 첫 프레임이 이미 왔는가(기동 2초가 끝났는가)."""
        with self._lock:
            return self._first_ts > 0.0

    def running(self):
        """살아 있는 스트림에만 True. 🔴 죽은 스트림에 True 를 주면 호출부가 재기동을 못 한다."""
        proc = self._proc
        if proc is None or self._reaped:
            return False                    # 아예 없거나, _feed 가 유휴로 내렸다
        try:
            return proc.poll() is None      # --time-limit 만료·crash 로 ffmpeg 이 죽었으면 False
        except Exception:
            return False

    def _idle_expired(self):
        """유휴 회수 판정. 🔴 첫 프레임 전(기동 2.1초)에는 절대 True 를 돌려주지 않는다."""
        with self._lock:
            first = self._first_ts
            if first <= 0.0:
                return False                # 아직 기동 중 - 스스로를 죽이면 안 된다
            base = self._last_use if self._last_use > first else first
        return (time.time() - base) > _MG_STREAM_IDLE_S

    def stop(self):
        """프로세스·스레드·소켓을 전부 정리한다. 여러 번 불러도 안전하다.

        🔴 순서가 전부다 - (1)소켓을 끊어 recv 로 잠든 수신 스레드를 깨우고 (2)ffmpeg 을 죽여
           read 로 잠든 읽기 스레드가 EOF 로 풀리게 한 뒤 (3)스레드를 거두고 (4)그제서야 파이프를
           닫는다. 블록된 read 밑에서 파이프 핸들을 먼저 닫으면 교착이 난다(실측: 파이썬·ffmpeg
           프로세스가 통째로 멈춰 수동 kill 로만 풀렸다).
        """
        proc, conn, evt, threads = self._proc, self._conn, self._evt, self._threads
        self._proc = self._conn = self._evt = None
        self._threads = []
        if evt is not None:
            evt.set()
        self._close_conn(conn)
        self._kill_proc(proc)
        for t in threads:
            try:
                t.join(timeout=2.0)
            except Exception:
                pass
        self._close_pipes(proc)
        self._reaped = False
        with self._lock:
            self._frame = None
            self._ts = 0.0
            self._first_ts = 0.0
            self._last_use = 0.0

    @staticmethod
    def _close_conn(conn):
        if conn is None:
            return
        try:
            conn.socket.shutdown(socket.SHUT_RDWR)   # recv 로 잠든 수신 스레드를 깨운다
        except Exception:
            pass
        try:
            conn.close()
        except Exception:
            pass

    @staticmethod
    def _kill_proc(proc):
        if proc is None:
            return
        try:
            proc.terminate()
        except Exception:
            pass
        try:
            proc.wait(timeout=2.0)
        except Exception:
            try:
                proc.kill()
            except Exception:
                pass

    @staticmethod
    def _close_pipes(proc):
        if proc is None:
            return
        for fh in (proc.stdin, proc.stdout):
            try:
                fh.close()
            except Exception:
                pass

    def _feed(self, conn, proc, evt):
        """adb 소켓 -> ffmpeg stdin. 🔴 부분 쓰기 루프 필수 - write() 가 전부 쓴다고 가정하지 마라."""
        sock, stdin = conn.socket, proc.stdin
        try:
            while not evt.is_set():
                # 🔴 유휴 회수. 이 루프는 데이터가 흐르면 수시로, 끊기면 소켓 타임아웃으로 1초마다
                #    깨어난다 = 검사할 자리가 여기다. 자기 자신을 join 하면 교착이므로 stop() 은
                #    절대 부르지 않는다 - 소켓·프로세스만 정리하고 빠진다(스레드 거두기는 다음 stop()).
                if self._idle_expired():
                    self._reaped = True      # running() -> False -> 호출부가 재기동할 수 있다
                    evt.set()                # 짝인 _read 도 깨운다
                    self._close_conn(conn)
                    self._kill_proc(proc)    # ffmpeg 사망 -> _read 는 EOF 로 알아서 풀린다
                    break
                try:
                    chunk = sock.recv(_MG_STREAM_CHUNK)
                except socket.timeout:
                    continue
                except Exception:
                    break
                if not chunk:
                    break                      # screenrecord 종료(--time-limit) 또는 연결 끊김
                view = memoryview(chunk)
                while view and not evt.is_set():
                    try:
                        n = stdin.write(view)
                    except Exception:
                        return                 # 파이프가 닫혔다 -> 조용히 끝낸다(폴백이 받는다)
                    if n is None:
                        break                  # 버퍼링 파일객체는 None = 전량 기록
                    if n <= 0:
                        time.sleep(0.001)
                        continue
                    view = view[n:]
        finally:
            try:
                stdin.close()                  # ffmpeg 이 EOF 를 보고 스스로 내려가게
            except Exception:
                pass

    def _read(self, proc, h, w, nbytes, evt):
        """ffmpeg stdout -> 최신 프레임 교체. 큐에 쌓지 않는다(낡은 프레임은 버린다)."""
        stdout = proc.stdout
        buf = bytearray(nbytes)
        view = memoryview(buf)
        while not evt.is_set():
            got = 0
            while got < nbytes:
                if evt.is_set():
                    return
                try:
                    n = stdout.readinto(view[got:])
                except Exception:
                    return
                if not n:
                    return                     # EOF/에러 -> 스레드 종료. 낡음 게이트가 뒤를 막는다.
                got += n
            frame = np.frombuffer(bytes(buf), dtype=np.uint8).reshape((h, w, 3))
            ts = time.time()
            with self._lock:
                self._frame = frame
                self._ts = ts
                if self._first_ts == 0.0:
                    self._first_ts = ts      # 여기부터가 '살아 있는 스트림' - 유휴 시계 기준선


