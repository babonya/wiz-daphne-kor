            over_max = step_px * _MG_OVERSHOOT_FRAMES
            sgn_v = 1.0 if v > 0 else -1.0

            # 🔴 [2026-09-20 (7)] 착지 산포. 건강하면 고정 28ms, 파이프라인이 밀리면 실측 p95.
            #    빗나감은 편향이 아니라 산포였다 - |v| 구간별 잔차 sd 25/36/36/67px 이
            #    `sigma = 28ms x |v|` 한 식에 수렴한다(28x1.0=28 vs 25 · 28x2.4=67 vs 67).
            sigma_ms, sigma_adapt = _mg_sigma_ms(dt_hist)
            sigma_px = sigma_ms * abs(v)

            hit = False
            f_early = f_passed = f_out = f_jitter = False
