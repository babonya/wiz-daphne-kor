            #      🔴 여유를 한 눈금(1.0)이 아니라 1.5 눈금으로 둔 이유는 프레임 간격이 고르지
            #      않기 때문이다(실측 p95 가 중앙값의 1.5배까지 벌어진다 - 25.8ms 중앙에 p95
            #      35.0ms). 1.0 으로 조이면 간격이 살짝 벌어진 프레임에서 멀쩡한 발사 기회를
            #      '지나침'으로 오판해 버린다.
            #    ------------------------------------------------------------------
