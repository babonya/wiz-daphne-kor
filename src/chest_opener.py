        #    노란 구간이 뒤늦게 밝아진다(실측: 페이드인 2프레임 동안 g최대 205->230->238).
        #    그래서 1차 스캔이 0개여도 폴백하지 않고 아래 루프에서 재스캔한다(임계는 건드리지 않는다).
        zones = _mg_find_zones(img_np)
